"""Model cards (PLAN.md 5.1): what a model is, how it was tested, by region.

A card is two files written together by ``python -m ml.evaluation
evaluate``: ``ml/cards/<id>.json`` (what CI compares: ops/model_gate.py
fails a pull request whose card is worse than the base branch's) and
``docs/model-cards/<id>.md`` (the same card for people, from ``render``,
the one template every card follows). Both are generated, never edited:
tests/test_model_cards.py re-evaluates every registered model and fails
when either file differs from what its trained files give.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Mapping, Optional

from ml.evaluation.harness import MIN_CASES

ROOT = Path(__file__).resolve().parent.parent.parent
CARDS = ROOT / "ml" / "cards"
DOCS = ROOT / "docs" / "model-cards"
REGISTRY = ROOT / "ml" / "registry.json"
CARD_FORMAT = 1

REGION_NAMES = {"us": "United States", "europe": "Europe", "emerging": "Emerging markets",
                "other_developed": "Other developed"}
VERDICT_TEXT = {"beats_baseline": "beats the baseline", "does_not_beat_baseline": "does not beat the baseline",
                "not_enough_data": "not enough data"}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def registry() -> dict:
    """``ml/registry.json``: every model the app loads, its trained files,
    its card and how it is trained."""
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def entry(model_id: str) -> dict:
    return next(m for m in registry()["models"] if m["id"] == model_id)


def artifacts(model: Mapping, base: Optional[Path] = None) -> list[dict]:
    """Each trained file's path, size and hash; ``base`` reads them from a
    scratch directory instead of the repository (a CI training run)."""
    out = []
    for rel in model["artifacts"]:
        path = (base / Path(rel).name) if base else ROOT / rel
        out.append({"path": rel, "bytes": path.stat().st_size, "sha256": sha256(path)})
    return out


def build(model: Mapping, about: Mapping, evaluation: Mapping, base: Optional[Path] = None) -> dict:
    """The card: what the model is (``about``, from its evaluation module),
    the files evaluated and the results."""
    return {"format": CARD_FORMAT, **about, "min_cases": MIN_CASES,
            "registry": {"artifacts": artifacts(model, base)}, "evaluation": dict(evaluation)}


def to_json(card: Mapping) -> str:
    return json.dumps(card, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def _fmt(x) -> str:
    return "–" if x is None else f"{x:.4g}" if isinstance(x, float) else str(x)


def _table(card: Mapping, set_name: str) -> list[str]:
    ev = card["evaluation"]
    group = ev["sets"][set_name]
    ids = [m["id"] for m in ev["metrics"]]
    head = ["Group", "Cases", "Verdict"] + [f"{i} (model / baseline)" for i in ids]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    rows = [("All regions", group["overall"])] + [
        (REGION_NAMES.get(r, r), g) for r, g in group["by_region"].items()]
    for name, g in rows:
        cells = [name, str(g["cases"]), VERDICT_TEXT[g["verdict"]]]
        for i in ids:
            if "model" in g:
                cells.append(f"{_fmt(g['model'][i])} / {_fmt(g['baseline'][i])}")
            else:
                cells.append("–")
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render(card: Mapping) -> str:
    """The card as Markdown, from the one template every card uses."""
    ev = card["evaluation"]
    split = ev["split"]
    if split["kind"] == "walk_forward":
        split_text = (f"Walk-forward by {split['dated_by']}: trained on cases before each cutoff "
                      f"({', '.join(str(c) for c in split['cutoffs'])}), tested on the cases from it "
                      "to the next.")
    else:
        split_text = f"No time split: {split['why']}."
    lines = [
        f"# Model card: {card['name']}",
        "",
        "Generated by `python -m ml.evaluation evaluate` from `ml/cards/"
        f"{card['id']}.json`; do not edit by hand (PLAN.md 5.1).",
        "",
        "| | |", "|---|---|",
        f"| Model | `{card['id']}` (`{card['module']}`) |",
        f"| Used by | {card['used_by']} |",
        f"| Estimates | {card['estimates']} |",
        f"| Training data | {card['training']['data']} |",
        f"| Trained by | `{card['training']['command']}` (GitHub Actions: `ml.yml`, train) |",
        f"| Retraining gives the same files | {'yes' if card['training']['deterministic'] else 'no'} |",
        "",
        "## How it is tested",
        "",
        f"- **Split:** {split_text}",
        f"- **Baseline:** {ev['baseline']['description']}.",
        f"- **Headline:** `{ev['headline_metric']}` on the `{ev['headline_set']}` set. A group "
        f"\"beats the baseline\" only when the model is strictly better there; under "
        f"{card['min_cases']} cases it has \"not enough data\" and the app should show no estimate.",
        "- **Regions:** S&P's (the validation report's): United States, Europe, emerging markets, "
        "other developed.",
        "",
        "Statistics:",
        "",
    ]
    for m in ev["metrics"]:
        lines.append(f"- `{m['id']}` ({m['better']} is better; CI fails a change that makes it worse "
                     f"by more than {m['tolerance']:g}): {m['description']}.")
    # The headline first, then the rest by name (the stored card's keys are sorted)
    order = [ev["headline_set"]] + sorted(k for k in ev["sets"] if k != ev["headline_set"])
    for set_name in order:
        group = ev["sets"][set_name]
        headline = " (headline)" if set_name == ev["headline_set"] else ""
        lines += ["", f"## Results: {set_name}{headline}", "", group["description"] + ".", ""]
        lines += _table(card, set_name)
    lines += ["", "## Limitations", ""]
    lines += [f"- {x}" for x in card["limitations"]]
    lines += ["", "## Files evaluated", "", "| File | Bytes | SHA-256 |", "|---|---|---|"]
    lines += [f"| `{a['path']}` | {a['bytes']:,} | `{a['sha256'][:16]}…` |" for a in card["registry"]["artifacts"]]
    return "\n".join(lines) + "\n"


def paths(model_id: str) -> tuple[Path, Path]:
    return CARDS / f"{model_id}.json", DOCS / f"{model_id}.md"


def write(card: Mapping, cards_dir: Path = CARDS, docs_dir: Path = DOCS) -> None:
    cards_dir.mkdir(parents=True, exist_ok=True)
    docs_dir.mkdir(parents=True, exist_ok=True)
    # "\n" on every platform, so a card written on Windows is the bytes CI writes
    (cards_dir / f"{card['id']}.json").write_text(to_json(card), encoding="utf-8", newline="\n")
    (docs_dir / f"{card['id']}.md").write_text(render(card), encoding="utf-8", newline="\n")
